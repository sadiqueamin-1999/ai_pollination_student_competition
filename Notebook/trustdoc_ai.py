def audit_agreements():

    findings = []

    for chunk in chunks:

        doc = chunk["document"]
        text = chunk["text"].lower()

        # Unsigned agreements

        if "awaiting signature" in text:

            findings.append({
                "severity": "HIGH",
                "document": doc,
                "issue": "Agreement awaiting signature"
            })

        if "draft v" in text:

            findings.append({
                "severity": "HIGH",
                "document": doc,
                "issue": "Draft agreement detected"
            })

        if (
            "signed agreement" in text
            and "outstanding" in text
        ):

            findings.append({
                "severity": "HIGH",
                "document": doc,
                "issue": "Signed agreement outstanding"
            })

        # Insurance checks

        if (
            "insurance" in text
            and "outstanding" in text
        ):

            findings.append({
                "severity": "MEDIUM",
                "document": doc,
                "issue": "Insurance documentation outstanding"
            })

        if (
            "public liability" in text
            and "outstanding" in text
        ):

            findings.append({
                "severity": "MEDIUM",
                "document": doc,
                "issue": "Public liability certificate outstanding"
            })

        # Risk assessment checks

        if (
            "risk assessment" in text
            and "outstanding" in text
        ):

            findings.append({
                "severity": "MEDIUM",
                "document": doc,
                "issue": "Risk assessment outstanding"
            })

        if (
            "rams" in text
            and "outstanding" in text
        ):

            findings.append({
                "severity": "MEDIUM",
                "document": doc,
                "issue": "RAMS documentation outstanding"
            })

        # Generic compliance failures

        if (
            "status:" in text
            and "outstanding" in text
        ):

            findings.append({
                "severity": "LOW",
                "document": doc,
                "issue": "Outstanding compliance item"
            })

    return findings

