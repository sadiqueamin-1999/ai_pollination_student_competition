def extract_pdf(file_path):

    pages = []

    pdf = fitz.open(file_path)

    for i in range(len(pdf)):

        text = pdf[i].get_text()

        if text.strip():

            pages.append({
                "document": os.path.basename(file_path),
                "page": i + 1,
                "text": text
            })

    return pages

def extract_docx(file_path):

    doc = Document(file_path)

    text = "\n".join(
        [p.text for p in doc.paragraphs]
    )

    return [{
        "document": os.path.basename(file_path),
        "page": 1,
        "text": text
    }]

